// Generates docs/import-rules.md from .dependency-cruiser.cjs, so the import table is written in one place only.
// Usage: node scripts/gen-import-rules.mjs          → write the file
//        node scripts/gen-import-rules.mjs --check  → exit 1 if the file is out of date (part of `pnpm verify`)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const config = require(join(root, '.dependency-cruiser.cjs'));
const target = join(root, 'docs', 'import-rules.md');

// Allow-rules carry their name as the start of the comment ("name — text"); forbidden rules have a `name` field.
const row = (rule) => {
  const [name, ...rest] = rule.name ? [rule.name, rule.comment] : rule.comment.split(' — ');
  return `| \`${name}\` | ${rest.join(' — ')} |`;
};

const content = [
  '# Import rules',
  '',
  '<!-- Generated by `pnpm gen:rules` from .dependency-cruiser.cjs. Do not edit by hand. -->',
  '',
  'An import is allowed only if one of these rules allows it. Anything else fails `pnpm verify`.',
  '',
  '| Rule | Allows |',
  '| --- | --- |',
  ...config.allowed.map(row),
  '',
  'Always forbidden:',
  '',
  '| Rule | Why |',
  '| --- | --- |',
  ...config.forbidden.map(row),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== content) {
    console.error(
      'docs/import-rules.md is out of date. Run `pnpm gen:rules` and commit the result.',
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, content);
  console.log('Wrote docs/import-rules.md');
}
